/**
 * Round-trip build+parse test for the generated Cloudflare Worker.
 *
 * Regression test for the broken-main incident (audit H5b):
 * src/lib/signer/runtime/providers.js contained an orphaned duplicate block
 * with illegal top-level `return` statements. Because generator.ts inlines
 * the runtime sources via `?raw` imports, nothing ever parsed them, so the
 * broken file shipped into every generated worker.
 *
 * This test mirrors generator.ts's buildWorkerSource() exactly (raw file
 * read + import/export stripping + concatenation) and asserts that both the
 * individual runtime sources and the assembled worker parse as an ES module.
 *
 * Run with: npm run test:syntax   (or: node --test test/)
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const runtimeDir = join(repoRoot, 'src', 'lib', 'signer', 'runtime');
const RUNTIME_FILES = ['core.js', 'providers.js', 'entry.js'];

/** Parse-check `source` as an ES module using a fresh node process. */
function assertParsesAsESM(source, label) {
  const dir = mkdtempSync(join(tmpdir(), 'leef-signer-'));
  try {
    const file = join(dir, 'check.mjs');
    writeFileSync(file, source);
    execFileSync(process.execPath, ['--check', file], { stdio: 'pipe' });
  } catch (e) {
    const stderr = e.stderr ? String(e.stderr) : String(e);
    assert.fail(`${label} does not parse as an ES module:\n${stderr}`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/* ------------------------------------------------------------------ */
/* Keep the two helpers below in sync with runtime/generator.ts.      */
/* ------------------------------------------------------------------ */

/** Strip `import ...;` statements (single- and multi-line). */
function stripImports(src) {
  let out = src.replace(/import\s+(?:type\s+)?\{[^}]*\}\s+from\s+['"][^'"]+['"];/g, '');
  out = out.replace(/^\s*import\s+[^;]*;\s*$/gm, '');
  out = out.replace(/declare\s+const\s+MANIFEST[^;]*;/g, '');
  return out;
}

/** Convert exported declarations into plain top-level declarations. */
function stripExports(src) {
  return src
    .replace(/export\s+default\s+/g, 'const __default_export__ = ')
    .replace(/export\s+(?=(async\s+)?(function|const|let|class|interface|type)\b)/g, '')
    .replace(/export\s*\{[^}]*\};?/g, '');
}

/** Mirror of generator.ts buildWorkerSource(). */
function buildWorkerSource(manifest, compatibilityDate = '2026-08-01') {
  const core = stripExports(stripImports(readFileSync(join(runtimeDir, 'core.js'), 'utf8')));
  const providers = stripExports(stripImports(readFileSync(join(runtimeDir, 'providers.js'), 'utf8')));
  let entry = stripExports(stripImports(readFileSync(join(runtimeDir, 'entry.js'), 'utf8')));
  entry = entry.replace('const __default_export__ =', 'const __worker =');
  const manifestJson = JSON.stringify(manifest, null, 2);

  return `/**
 * ${manifest.app} — generated by LEEF Trader Signer (runtime v${manifest.runtimeVersion}).
 *
 * DO NOT EDIT BY HAND. This file is generated from a non-secret manifest.
 * Provider credentials are NOT in this file — they are Cloudflare Worker
 * Secrets read at runtime via env.*.
 */
'use strict';

/* ===== runtime/core ===== */
${core}

/* ===== runtime/providers ===== */
${providers}

/* ===== manifest (non-secret) ===== */
const MANIFEST = ${manifestJson};

/* ===== runtime/entry ===== */
${entry}

export default __worker;

/* compatibility_date: ${compatibilityDate} */
`;
}

test('each runtime source parses as an ES module', () => {
  for (const name of RUNTIME_FILES) {
    assertParsesAsESM(readFileSync(join(runtimeDir, name), 'utf8'), `runtime/${name}`);
  }
});

test('generated worker source parses as an ES module (round-trip)', () => {
  const manifest = {
    version: '1',
    app: 'roundtrip-test',
    runtimeVersion: '0.0.0-test',
    security: { allowedOrigins: ['https://example.com'], publicAuth: { type: 'none' }, internalMode: false },
    limits: { default: { keyBy: 'ip', requestsPerMinute: 60 }, perRoute: {} },
    privacy: { mode: 'standard' },
    routes: {},
    providers: {},
  };
  const workerSource = buildWorkerSource(manifest);
  assertParsesAsESM(workerSource, 'generated worker source');
  // The entry default export must survive the strip/rename pipeline.
  assert.match(workerSource, /const __worker =/);
  assert.match(workerSource, /export default __worker;/);
});
